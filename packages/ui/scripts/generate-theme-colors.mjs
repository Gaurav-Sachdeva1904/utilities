import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, '..');

const themeFiles = {
    light: path.join(packageRoot, 'src/styles/theme/light.scss'),
    dark: path.join(packageRoot, 'src/styles/theme/dark.scss'),
};

const outputFile = path.join(packageRoot, 'src/styles/theme/generatedThemeColors.ts');

const COLOR_VALUE_PATTERN = /^(#(?:[0-9a-f]{3,8})|var\(--[\w-]+\))$/i;
const VARIABLE_PATTERN = /^\s*(--[\w-]+):\s*([^;]+);/;

function toLabel(cssVar) {
    return cssVar
        .replace(/^--/, '')
        .split('-')
        .map(part =>
            part.toUpperCase() === part || /^\d+$/.test(part)
                ? part
                : part[0].toUpperCase() + part.slice(1),
        )
        .join(' ');
}

async function collectThemeColorVars() {
    const ordered = new Map();

    for (const [theme, file] of Object.entries(themeFiles)) {
        const content = await readFile(file, 'utf8');

        for (const line of content.split('\n')) {
            const match = line.match(VARIABLE_PATTERN);
            if (!match) {
                continue;
            }

            const [, cssVar, rawValue] = match;
            const value = rawValue.trim();

            if (!COLOR_VALUE_PATTERN.test(value)) {
                continue;
            }

            const key = cssVar.replace(/^--/, '');

            if (!ordered.has(key)) {
                ordered.set(key, {
                    key,
                    label: toLabel(cssVar),
                    cssVar,
                    value: {},
                });
            }

            ordered.get(key).value[theme] = value;
        }
    }

    return ordered;
}

async function main() {
    const colors = await collectThemeColorVars();
    const fileContents = `// This file is auto-generated by packages/ui/scripts/generate-theme-colors.mjs.
// Do not edit it manually.

export type ThemeColorToken = {
    key: string;
    label: string;
    cssVar: string;
    value?: {
        light?: string;
        dark?: string;
    };
};

export const themeColorTokens: Record<string, ThemeColorToken> = ${JSON.stringify(Object.fromEntries(colors), null, 4)} as const;
`;

    await mkdir(path.dirname(outputFile), { recursive: true });
    await writeFile(outputFile, fileContents);
}

main().catch(error => {
    console.error(error);
    process.exitCode = 1;
});
